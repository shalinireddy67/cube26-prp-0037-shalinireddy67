"""
Evaluation Runner for Prep Manager.

Runs photos from data/eval_labels.csv through analyze_unit_photo(), compares
observations against expected labels, tallies per-check and overall metrics,
and outputs a markdown report to docs/eval-report.md.
"""

import csv
import os
import sys
from pathlib import Path
from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

load_dotenv()

from src.vision_agent import analyze_unit_photo

CHECKS = [
    "polybag_present_sealed",
    "suffocation_warning",
    "fnsku_label_placement",
    "original_barcode_covered",
    "expiry_date",
    "handling_marks",
]


def run_evaluation() -> None:
    csv_path = PROJECT_ROOT / "data" / "eval_labels.csv"
    report_path = PROJECT_ROOT / "docs" / "eval-report.md"

    if not csv_path.is_file():
        print(f"Error: Label file not found at {csv_path}", file=sys.stderr)
        sys.exit(1)

    with open(csv_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    vision_provider = os.environ.get("VISION_PROVIDER", "gemini")

    total_images = len(rows)
    model_failures: list[tuple[str, str]] = []

    stats: dict[str, dict[str, int]] = {
        check: {
            "labeled": 0,
            "matches": 0,
            "cautious_miss": 0,
            "overconfident_miss": 0,
            "wrong_observation": 0,
        }
        for check in CHECKS
    }

    mismatches: list[str] = []

    for row in rows:
        image_filename = row.get("image_filename", "").strip()
        if not image_filename:
            continue

        image_path = PROJECT_ROOT / "fixtures" / "prep" / image_filename
        if not image_path.is_file():
            image_path = Path(image_filename)

        print(f"Evaluating {image_filename}...")
        result = analyze_unit_photo(str(image_path))

        status = result.get("status")
        if status == "PENDING":
            reason = result.get("reason", "Unknown error / pending status")
            model_failures.append((image_filename, reason))
            continue

        if status != "OK":
            reason = result.get("reason", f"Unexpected status: {status}")
            model_failures.append((image_filename, reason))
            continue

        checks_data = result.get("checks", {})
        for check_name in CHECKS:
            expected_key = f"expected_{check_name}"
            expected_val = row.get(expected_key, "").strip()

            if not expected_val:
                continue

            stats[check_name]["labeled"] += 1
            actual_val = checks_data.get(check_name, {}).get("observation", "").strip()

            if actual_val == expected_val:
                stats[check_name]["matches"] += 1
            elif actual_val == "uncertain" and expected_val != "uncertain":
                stats[check_name]["cautious_miss"] += 1
                mismatches.append(
                    f"{image_filename} | {check_name} | expected={expected_val} actual={actual_val} | cautious_miss"
                )
            elif expected_val == "uncertain" and actual_val != "uncertain":
                stats[check_name]["overconfident_miss"] += 1
                mismatches.append(
                    f"{image_filename} | {check_name} | expected={expected_val} actual={actual_val} | overconfident_miss"
                )
            else:
                stats[check_name]["wrong_observation"] += 1
                mismatches.append(
                    f"{image_filename} | {check_name} | expected={expected_val} actual={actual_val} | wrong_observation"
                )

    overall = {
        "labeled": sum(stats[c]["labeled"] for c in CHECKS),
        "matches": sum(stats[c]["matches"] for c in CHECKS),
        "cautious_miss": sum(stats[c]["cautious_miss"] for c in CHECKS),
        "overconfident_miss": sum(stats[c]["overconfident_miss"] for c in CHECKS),
        "wrong_observation": sum(stats[c]["wrong_observation"] for c in CHECKS),
    }

    lines: list[str] = [
        "# Prep Manager — Evaluation Report",
        "",
        "Generated by eval/run_eval.py against data/eval_labels.csv.",
        f"Vision provider used: {vision_provider}.",
        "",
        "## Summary",
        f"- Total images evaluated: {total_images}",
        f"- Model failures (PENDING): {len(model_failures)}",
        f"- Total labeled checks scored: {overall['labeled']}",
        "",
        "## Per-check results",
        "| check_name | labeled | matches | match_rate | cautious_miss | overconfident_miss | wrong_observation |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: |",
    ]

    for check_name in CHECKS:
        s = stats[check_name]
        rate_str = f"{(s['matches'] / s['labeled'] * 100):.1f}%" if s["labeled"] > 0 else "0.0%"
        lines.append(
            f"| {check_name} | {s['labeled']} | {s['matches']} | {rate_str} | {s['cautious_miss']} | {s['overconfident_miss']} | {s['wrong_observation']} |"
        )

    lines.extend([
        "",
        "## Overall totals",
        "| check_name | labeled | matches | match_rate | cautious_miss | overconfident_miss | wrong_observation |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: |",
    ])
    overall_rate_str = (
        f"{(overall['matches'] / overall['labeled'] * 100):.1f}%" if overall["labeled"] > 0 else "0.0%"
    )
    lines.append(
        f"| Overall | {overall['labeled']} | {overall['matches']} | {overall_rate_str} | {overall['cautious_miss']} | {overall['overconfident_miss']} | {overall['wrong_observation']} |"
    )

    lines.extend([
        "",
        "## Individual mismatches",
    ])
    if mismatches:
        for m in mismatches:
            lines.append(f"- `{m}`")
    else:
        lines.append("- None.")

    lines.extend([
        "",
        "## Model failures",
    ])
    if model_failures:
        for fname, rsn in model_failures:
            lines.append(f"- `{fname}`: {rsn}")
    else:
        lines.append("- None.")

    lines.extend([
        "",
        "## Limitations",
        f"This evaluation covers {total_images} images the project owner staged and labeled by hand, not an independent held-out set scored by multiple people. Small sample size — treat percentages as directional, not statistically robust.",
        "",
    ])

    report_content = "\n".join(lines)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report_content, encoding="utf-8")

    print("\n" + "=" * 50)
    print("PREP MANAGER — EVALUATION REPORT")
    print("=" * 50)
    print(f"Vision provider: {vision_provider}")
    print(f"Total images evaluated: {total_images}")
    print(f"Model failures (PENDING): {len(model_failures)}")
    print(f"Total labeled checks scored: {overall['labeled']}")
    print("-" * 50)
    print(
        f"{'check_name':<26} | {'labeled':<7} | {'matches':<7} | {'rate':<7} | {'cautious':<8} | {'overconf':<8} | {'wrong':<5}"
    )
    print("-" * 80)
    for check_name in CHECKS:
        s = stats[check_name]
        rate_str = f"{(s['matches'] / s['labeled'] * 100):.1f}%" if s["labeled"] > 0 else "0.0%"
        print(
            f"{check_name:<26} | {s['labeled']:<7} | {s['matches']:<7} | {rate_str:<7} | {s['cautious_miss']:<8} | {s['overconfident_miss']:<8} | {s['wrong_observation']:<5}"
        )
    print("-" * 80)
    print(
        f"{'Overall':<26} | {overall['labeled']:<7} | {overall['matches']:<7} | {overall_rate_str:<7} | {overall['cautious_miss']:<8} | {overall['overconfident_miss']:<8} | {overall['wrong_observation']:<5}"
    )
    print("=" * 50)
    print(f"Report written to: {report_path}")


if __name__ == "__main__":
    run_evaluation()
